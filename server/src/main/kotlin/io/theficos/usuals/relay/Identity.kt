package io.theficos.usuals.relay

import com.google.crypto.tink.subtle.Ed25519Sign
import com.google.crypto.tink.subtle.Ed25519Verify
import com.google.crypto.tink.subtle.Random
import io.theficos.usuals.sync.*
import java.nio.file.Files
import java.nio.file.Path
import java.net.URI

class Identity(private val seed: ByteArray, val publicKey: ByteArray) {
    val serverId = Wire.hash(publicKey)
    fun info() = ServerInfo(serverId, Wire.encode(publicKey))
    fun sign(bytes: ByteArray): String = Wire.encode(Ed25519Sign(seed).sign(bytes))
    companion object {
        fun generate(): Identity = Ed25519Sign.KeyPair.newKeyPair().let { Identity(it.privateKey, it.publicKey) }
        fun load(path: Path): Identity {
            // Generated by the explicit local init command. Startup never silently changes identity.
            val bytes = Files.readAllBytes(path); require(bytes.size == 64)
            val result = Identity(bytes.copyOfRange(0, 32), bytes.copyOfRange(32, 64))
            verify(Wire.encode(result.publicKey), result.sign(byteArrayOf(1)), byteArrayOf(1))
            return result
        }
        fun create(path: Path) {
            val pair = Ed25519Sign.KeyPair.newKeyPair()
            Files.createFile(path, java.nio.file.attribute.PosixFilePermissions.asFileAttribute(java.nio.file.attribute.PosixFilePermissions.fromString("rw-------")))
            java.nio.channels.FileChannel.open(path, java.nio.file.StandardOpenOption.WRITE).use { channel ->
                val bytes = java.nio.ByteBuffer.wrap(pair.privateKey + pair.publicKey)
                while (bytes.hasRemaining()) channel.write(bytes)
                channel.force(true)
            }
            java.nio.channels.FileChannel.open(path.toAbsolutePath().parent, java.nio.file.StandardOpenOption.READ).use { it.force(true) }
        }
    }
}
internal fun randomToken() = Wire.encode(Random.randBytes(32))
internal fun verify(publicKey: String, signature: String, data: ByteArray) {
    try { Ed25519Verify(Wire.decode(publicKey, 32)).verify(Wire.decode(signature, 64), data) }
    catch (_: java.security.GeneralSecurityException) { reject("forbidden", 403) }
}
internal fun canonicalOrigin(value: String, local: Boolean = false): String {
    val u = URI(value)
    val loopback = u.host in setOf("localhost", "127.0.0.1", "10.0.2.2")
    require((u.scheme == "https" || local && u.scheme == "http" && loopback) && u.host != null &&
        u.host == u.host.lowercase() && u.host.all { it.code < 128 } && u.rawUserInfo == null &&
        (u.port == -1 || u.port in 1..65535) && u.rawPath.isNullOrEmpty() && u.rawQuery == null && u.rawFragment == null && !(u.scheme == "https" && u.port == 443))
    require(value == u.toASCIIString())
    return value
}
